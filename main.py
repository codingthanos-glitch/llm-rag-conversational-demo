# sqlite3 is Python's built-in library for working with SQLite databases.
# We use it to save and load conversation history.
import sqlite3

# Path provides an easy way to work with file and folder paths.
# We use it to check whether the PDF file exists.
from pathlib import Path

# pdfplumber is used to open PDF files and extract text from their pages.
import pdfplumber

# HumanMessage represents a message sent by the user.
# AIMessage represents a message generated by the AI.
from langchain_core.messages import AIMessage, HumanMessage

# Document is a LangChain object used to store:
#   1. The actual text in page_content
#   2. Additional information in metadata
from langchain_core.documents import Document

# ChatPromptTemplate creates a structured chat prompt.
# MessagesPlaceholder allows us to insert previous conversation messages
# dynamically into the prompt.
from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder

# FAISS is a vector database/vector store.
# It stores embeddings and helps retrieve the most relevant PDF chunks.
from langchain_community.vectorstores import FAISS

# RecursiveCharacterTextSplitter splits large documents into smaller chunks.
from langchain_text_splitters import RecursiveCharacterTextSplitter

# HuggingFaceEmbeddings converts text into numerical vector embeddings.
from langchain_huggingface import HuggingFaceEmbeddings

# ChatOllama allows LangChain to communicate with a locally running
# Ollama language model.
from langchain_ollama import ChatOllama


